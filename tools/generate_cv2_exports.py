"""Generate ``cv2u/_cv2_exports.pyi`` from the type stubs shipped with opencv-python.

At runtime ``cv2u`` forwards unknown attributes to ``cv2`` through a module ``__getattr__``.
Type checkers cannot see through that, and ``cv2/__init__.pyi`` declares ``__all__ = []``,
so ``from cv2 import *`` does not help either. This script lists every public name in the
OpenCV stub and re-exports it explicitly, so ``import cv2u as cv; cv.imread`` keeps the
OpenCV signature in IDEs and type checkers.

It is generated from the first OpenCV 5 release. Names that are not listed (added in later
releases, or only present in OpenCV 4, which cv2u also supports) still resolve at runtime
through ``__getattr__`` and are typed as ``Any``.

Usage::

    pip install "opencv-python==5.0.0.93"
    python tools/generate_cv2_exports.py           # write the file
    python tools/generate_cv2_exports.py --check   # fail if the file is out of date
"""

import argparse
import ast
import importlib.metadata
import importlib.util
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "cv2u" / "_cv2_exports.pyi"


def _stub_path() -> Path:
    spec = importlib.util.find_spec("cv2")
    if spec is None or spec.origin is None:
        raise SystemExit("opencv-python is not installed")
    stub = Path(spec.origin).with_name("__init__.pyi")
    if not stub.is_file():
        raise SystemExit(f"OpenCV type stub not found: {stub}")
    return stub


def _public_names(tree: ast.Module) -> set[str]:
    names: set[str] = set()

    def visit(body: list[ast.stmt]) -> None:
        for node in body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                names.add(node.name)
            elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
                names.add(node.target.id)
            elif isinstance(node, ast.Assign):
                names.update(t.id for t in node.targets if isinstance(t, ast.Name))
            elif isinstance(node, ast.ImportFrom) and node.module and node.module.split(".")[0] == "cv2":
                # In stubs, only ``from x import y as y`` is a re-export.
                names.update(a.asname for a in node.names if a.asname and a.asname == a.name)
            elif isinstance(node, ast.If):
                visit(node.body)
                visit(node.orelse)

    visit(tree.body)
    return {n for n in names if not n.startswith("_")}


def render() -> str:
    stub = _stub_path()
    names = sorted(_public_names(ast.parse(stub.read_text(encoding="utf-8"))))
    version = importlib.metadata.version("opencv-python")
    lines = [
        f"# Generated by tools/generate_cv2_exports.py from the opencv-python {version} type stubs.",
        "# Do not edit by hand. Regenerate with: python tools/generate_cv2_exports.py",
        "",
        "from cv2 import (",
        *(f"    {n} as {n}," for n in names),
        ")",
        "",
        "__all__ = [",
        *(f'    "{n}",' for n in names),
        "]",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit with 1 if the file is out of date")
    args = parser.parse_args()

    content = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print(f"{OUTPUT.name} is out of date. Run: python tools/generate_cv2_exports.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.name} is up to date")
        return 0

    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT} ({content.count(' as ')} names)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
